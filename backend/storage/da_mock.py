def load(industries: Optional[Iterable[str]] = None, *, overwrite: bool = False,
         with_projects: bool = True) -> dict[str, dict[str, int]]:
    """把指定行业的源表数据写入库(幂等)。返回每个行业的写入计数。"""
    keys = list(industries) if industries else list(INDUSTRIES)
    unknown = [k for k in keys if k not in INDUSTRIES]
    if unknown:
        raise ValueError(f"未知行业: {unknown};可选 {list(INDUSTRIES)}")
    return {k: _load_one(INDUSTRIES[k], overwrite=overwrite, with_projects=with_projects)
            for k in keys}


def _load_one(pack: dict, *, overwrite: bool, with_projects: bool) -> dict[str, int]:
    counts: dict[str, int] = {}

    for code, name, category in pack["equipment_classes"]:
        db.upsert("kb_equipment_class", {"class_code": code, "name": name, "category": category},
                  keys=("class_code",))
    counts["设备类别"] = len(pack["equipment_classes"])

    counts["设备"] = _each(
        pack["equipment"], overwrite,
        exists=lambda i: db.query_one(
            "SELECT equipment_id FROM kb_equipment WHERE equipment_code = ?", (i["equipment_code"],)),
        save=lambda i, row: kb.save_equipment({**i, **row}),
        id_key="equipment_id",
    )

    material_count = price_count = 0
    for entry in pack["materials"]:
        code = entry["material"]["material_code"]
        if db.query_one("SELECT material_code FROM kb_material WHERE material_code = ?", (code,)) \
                and not overwrite:
            continue
        kb.save_material(entry["material"], properties=entry.get("properties"))
        lib.material_dir(code, create=True)
        material_count += 1
        for price in entry.get("prices") or []:
            existing = db.query_one(
                "SELECT price_id FROM kb_material_price WHERE material_code = ? AND valid_from = ?",
                (code, price.get("valid_from") or MOCK_DATE),
            )
            if existing:
                continue
            kb.add_material_price({**price, "material_code": code,
                                   "valid_from": price.get("valid_from") or MOCK_DATE})
            price_count += 1
    counts["物料"] = material_count
    counts["物料价格"] = price_count

    counts["工序"] = _each(
        pack["process_steps"], overwrite,
        exists=lambda i: db.query_one(
            "SELECT step_code FROM kb_process_step WHERE step_code = ?", (i["step_code"],)),
        save=lambda i, _row: kb.save_process_step({**i, "effective_from": MOCK_DATE}),
    )

    route_count = 0
    for entry in pack["routes"]:
        code = entry["route"]["route_code"]
        if db.query_one("SELECT route_code FROM kb_process_route WHERE route_code = ?", (code,)) \
                and not overwrite:
            continue
        kb.save_route(entry["route"], entry["steps"])
        lib.route_dir(code, create=True)
        route_count += 1
    counts["工艺路线"] = route_count

    component_count = 0
    for entry in pack["components"]:
        code = entry["component"]["component_code"]
        if db.query_one("SELECT component_id FROM kb_component WHERE component_code = ?", (code,)) \
                and not overwrite:
            continue
        kb.save_component(entry["component"], params=entry["params"], features=entry["features"])
        component_count += 1
    counts["零部件"] = component_count

    supplier_count = 0
    for entry in pack["suppliers"]:
        existing = db.query_one("SELECT supplier_id FROM kb_supplier WHERE name = ?",
                                (entry["supplier"]["name"],))
        if existing and not overwrite:
            continue
        row = dict(entry["supplier"])
        if existing:
            row["supplier_id"] = existing["supplier_id"]
        kb.save_supplier(row, capabilities=entry["capabilities"])
        supplier_count += 1
    counts["供应商"] = supplier_count

    counts["费率"] = _each(
        pack["cost_rates"], overwrite,
        exists=lambda i: db.query_one(
            "SELECT rate_code FROM kb_cost_rate WHERE rate_code = ?", (i["rate_code"],)),
        save=lambda i, _row: kb.save_cost_rate({**i, "effective_from": MOCK_DATE}),
    )
    counts["计价系数"] = _each(
        pack["cost_factors"], overwrite,
        exists=lambda i: db.query_one(
            "SELECT factor_code FROM kb_cost_factor WHERE factor_code = ?", (i["factor_code"],)),
        save=lambda i, _row: kb.save_cost_factor({**i, "effective_from": MOCK_DATE}),
    )

    if with_projects and pack.get("project"):
        counts["评估需求"] = _load_project(pack)
    return counts


def _each(items, overwrite: bool, *, exists, save, id_key: str = "") -> int:
    """通用的"存在则跳过/覆盖"循环。"""
    count = 0
    for item in items:
        found = exists(item)
        if found and not overwrite:
            continue
        row = {id_key: found[id_key]} if (found and id_key) else {}
        save(item, row)
        count += 1
    return count


