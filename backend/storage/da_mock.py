def _load_project(pack: dict) -> int:
    """写入该行业的一份评估需求(src_ 层),并把需求正文落成真实的输入文件。"""
    info = pack["project"]
    project_id = info["project_id"]
    repo.ensure_project(project_id, {
        "name": info["name"], "customer": info.get("customer"), "owner": info.get("owner"),
        "stage": "1.1", "created_at": MOCK_DATE,
    })
    industry = info.get("industry") or pack["key"]
    repo.save_requirement({
        "project_id": project_id,
        "requirement_no": info["requirement_no"],
        "title": info["title"],
        "status": "approved",
        "industry": industry,
        "data": {**info["fields"], "industry": industry},
        "created_by": "工艺技术经理",
        "created_at": MOCK_DATE,
        "confirmed_by": "工艺技术经理",
        "confirmed_at": MOCK_DATE,
        "reviewed_by": "工艺技术总监",
        "reviewed_at": MOCK_DATE,
        "review_note": info.get("note", ""),
    })

    # 输入文件必须真实存在才登记 —— 指向不存在的路径就是脏数据。
    input_dir = lib.blob_root() / project_id / "input"
    input_dir.mkdir(parents=True, exist_ok=True)
    target = input_dir / "requirement.txt"
    lines = [f"# {info['title']}", "", f"项目名称: {info['name']}",
             f"需求编号: {info['requirement_no']}", f"行业模板: {industry}",
             f"客户: {info.get('customer', '')}", ""]
    labels = _field_labels()
    lines += [f"{labels.get(k, k)}: {v}" for k, v in info["fields"].items()]
    if info.get("note"):
        lines += ["", f"备注: {info['note']}"]
    target.write_text("\n".join(lines), encoding="utf-8")

    already = db.query_one(
        "SELECT file_id FROM src_input_file WHERE project_id = ? AND file_path = ?",
        (project_id, lib.rel_path(target)),
    )
    if not already:
        repo.register_input_file(
            project_id, file_kind="tech_doc", filename="需求说明.txt",
            file_path=lib.rel_path(target), sha256=lib.sha256_file(target),
            size=target.stat().st_size, mime="text/plain", uploaded_by="工艺技术经理",
        )
    return 1
